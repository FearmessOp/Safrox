//! An 8x16 bitmap font, ASCII 0x20..=0x7F.
//!
//! The classic IBM VGA text-mode cell: eight pixels wide, sixteen
//! rows tall, one byte per row, **bit 7 is the leftmost pixel**.
//!
//! # Why a table in the source
//!
//! `include_bytes!` of a `.bin` was the alternative and it adds a
//! build-order dependency for no gain. As a Rust array the font is
//! diffable: a change to a glyph shows up in review as a changed
//! row, not as a changed blob.
//!
//! No TrueType. A rasteriser is a milestone of its own and a
//! terminal wants a fixed-width bitmap anyway.
//!
//! # What the acceptance test can and cannot prove about this
//!
//! **It cannot prove the glyphs are legible.** Criterion 4 reads
//! pixels back from the framebuffer and compares them against this
//! table, so the table is both the source of the drawing and the
//! reference for the check. A glyph that is wrong *here* is drawn
//! wrong and verified wrong, and the test passes.
//!
//! What the test does prove is that the drawing path applies the
//! table faithfully: the right bits, at the right address, in the
//! right cell. That is the part that can break silently; a mangled
//! letter 'A' is visible to anyone who looks at the screen.
//!
//! Stated here rather than left implicit, because "the test checks
//! the font" is exactly the sort of claim that sounds true and is
//! not (ADR 054).

/// Pixels across one character cell.
pub const WIDTH: u64 = 8;
/// Pixels down one character cell.
pub const HEIGHT: u64 = 16;

/// The first character the table covers.
pub const FIRST: u8 = 0x20;
/// The last character the table covers.
pub const LAST: u8 = 0x7F;

/// The glyph for `ch`, or the glyph for a space if it is outside the
/// table.
///
/// A space rather than a replacement box: an unprintable byte
/// reaching here is a bug in the caller, and a box would make the
/// screen look as though the bug were the user's. The keyboard
/// already filters non-characters (ADR 053), so nothing should.
pub fn glyph(ch: u8) -> &'static [u8; 16] {
    if ch < FIRST || ch > LAST {
        return &GLYPHS[0];
    }
    &GLYPHS[(ch - FIRST) as usize]
}

/// Whether a pixel of a glyph is set.
///
/// `x` is 0..8 from the left, `y` is 0..16 from the top. Out of
/// range is false rather than a panic: the callers that sample a
/// glyph for verification deliberately look just outside the cell.
pub fn pixel(ch: u8, x: u64, y: u64) -> bool {
    if x >= WIDTH || y >= HEIGHT {
        return false;
    }
    let row = glyph(ch)[y as usize];
    row & (0x80 >> x) != 0
}

