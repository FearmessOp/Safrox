/// A glyph with set and clear pixels that the verifier can sample.
///
/// Returns `(x, y)` pairs: four pixels the glyph sets and two it
/// leaves clear, all inside the 8x16 cell. The caller reads these
/// back from the real framebuffer (ADR 054).
///
/// # Why both kinds
///
/// Sampling only set pixels passes for a cell painted solid white.
/// Sampling only clear ones passes for a cell left black. Neither
/// alone distinguishes a drawn glyph from a uniform fill, which is
/// the failure a careless blit produces.
///
/// Returns `None` for a glyph without enough of each — a space has
/// no set pixels at all, and a verifier that silently sampled
/// nothing would report success having checked nothing.
pub fn sample_points(ch: u8) -> Option<([(u64, u64); 4], [(u64, u64); 2])> {
    let mut set = [(0u64, 0u64); 4];
    let mut clear = [(0u64, 0u64); 2];
    let mut set_count = 0usize;
    let mut clear_count = 0usize;

    // Walk the cell in a fixed order so the choice is reproducible:
    // the same character always yields the same sample points, which
    // means a failure names the same pixel every run.
    //
    // Set pixels are taken from different rows where possible —
    // stepping y by 4 — so that a blit which gets one row right and
    // the rest wrong does not pass. Clear pixels are taken from the
    // middle rows, inside the glyph's body rather than from the
    // blank border, where almost anything would be clear.
    for y in 0..HEIGHT {
        for x in 0..WIDTH {
            if pixel(ch, x, y) {
                if set_count < set.len() && (y % 4 == 0 || set_count == 0) {
                    set[set_count] = (x, y);
                    set_count += 1;
                }
            } else if clear_count < clear.len() && (4..12).contains(&y) {
                clear[clear_count] = (x, y);
                clear_count += 1;
            }
        }
    }

    // A second pass for the set pixels if the row filter was too
    // strict — a narrow glyph may have fewer than four rows matching
    // `y % 4`. Correctness before elegance: the alternative is
    // returning None for a glyph that is perfectly checkable.
    if set_count < set.len() {
        for y in 0..HEIGHT {
            for x in 0..WIDTH {
                if set_count >= set.len() {
                    break;
                }
                if pixel(ch, x, y) && !set[..set_count].contains(&(x, y)) {
                    set[set_count] = (x, y);
                    set_count += 1;
                }
            }
        }
    }

    if set_count < set.len() || clear_count < clear.len() {
        return None;
    }
    Some((set, clear))
}